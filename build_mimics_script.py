"""Build the single-file Mimics script: density_core.py + mimics_runner.py -> mimics_scripts/Mapa_densidad_metodo_C.py

    py -3.10 build_mimics_script.py

One file because Mimics lists EVERY .py in the Scripting Library folder as a menu entry (so the core
can't sit next to it as a module), and a library script runs in its own namespace.
Re-run after any change to density_core.py or mimics_runner.py.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'mimics_scripts', 'Mapa_densidad_metodo_C.py')

core = open(os.path.join(HERE, 'density_core.py'), encoding='utf-8').read()
runner = open(os.path.join(HERE, 'mimics_runner.py'), encoding='utf-8').read()
head = ('# Mapa de densidad (método C) - script de Mimics. GENERATED by build_mimics_script.py from\n'
        '# density_core.py + mimics_runner.py (NuriaFusion/DensityMap). Edit those, then rebuild.\n\n')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write(head + core + '\n\n' + runner)
compile(head + core + '\n\n' + runner, OUT, 'exec')       # syntax check
print('written', OUT)
